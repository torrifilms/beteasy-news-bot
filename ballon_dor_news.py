def upload_image(client, url, title):
    try:
        img = client.get(url, timeout=15, follow_redirects=True, headers=HEADERS)
        if img.status_code != 200 or len(img.content) < 3000:
            return None
        safe = slugify(title)[:40] or "news"
        r = client.post(
            f"{WP_URL}/wp-json/wp/v2/media",
            content=img.content,
            headers={
                "Content-Disposition": f'attachment; filename="{safe}.jpg"',
                "Content-Type": "image/jpeg",
            },
            auth=AUTH,
        )
        if r.status_code in (200, 201):
            return r.json().get("id")
    except Exception as e:
        print(f"  img err: {e}")
    return None

def main():
    with httpx.Client(timeout=60) as client:
        published = 0
        for item in NEWS:
            slug = slugify(item["title"])
            print(f"\n→ {item['title'][:50]}")
            # check exists
            r = client.get(f"{WP_URL}/wp-json/wp/v2/posts", params={"slug": slug}, auth=AUTH)
            if r.status_code == 200 and r.json():
                print("  SKIP (уже есть)")
                continue
            media_id = upload_image(client, item["img"], item["title"])
            payload = {
                "title": item["title"],
                "content": item["content"],
                "status": "publish",
                "slug": slug,
                "categories": [16],
            }
            if media_id:
                payload["featured_media"] = media_id
                print(f"  media={media_id}")
            r = client.post(f"{WP_URL}/wp-json/wp/v2/posts", json=payload, auth=AUTH)
            if r.status_code in (200, 201):
                print(f"  OK")
                published += 1
            else:
                print(f"  ERR {r.status_code}")
            time.sleep(1)
        print(f"\nОпубликовано: {published}")

if __name__ == "__main__":
    main()
