def upload_image(client, title):
    # Simple placeholder via Unsplash
    url = "https://images.unsplash.com/photo-1574629810360-7efbbe195018?w=800&h=500&fit=crop"
    try:
        img = client.get(url, timeout=10, follow_redirects=True, headers=HEADERS)
        if img.status_code == 200 and len(img.content) > 2000:
            safe = slugify(title)[:30]
            r = client.post(
                f"{WP_URL}/wp-json/wp/v2/media",
                content=img.content,
                headers={"Content-Disposition": f'attachment; filename="{safe}.jpg"', "Content-Type": "image/jpeg"},
                auth=AUTH,
            )
            if r.status_code in (200, 201):
                return r.json().get("id")
    except Exception:
        pass
    return None

def main():
    with httpx.Client(timeout=60) as client:
        published = 0
        for item in PAGES:
            slug = slugify(item["title"])
            print(f"→ {item['title'][:45]}")
            r = client.get(f"{WP_URL}/wp-json/wp/v2/posts", params={"slug": slug}, auth=AUTH)
            if r.status_code == 200 and r.json():
                print("  SKIP")
                continue
            media_id = upload_image(client, item["title"])
            payload = {
                "title": item["title"],
                "content": item["content"],
                "status": "publish",
                "slug": slug,
                "categories": [16],
            }
            if media_id:
                payload["featured_media"] = media_id
            r = client.post(f"{WP_URL}/wp-json/wp/v2/posts", json=payload, auth=AUTH)
            if r.status_code in (200, 201):
                print("  OK")
                published += 1
            else:
                print(f"  ERR {r.status_code}")
            time.sleep(0.8)
        print(f"\nОпубликовано: {published}")

if __name__ == "__main__":
    main()
