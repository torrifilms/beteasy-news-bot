def upload_image(client: httpx.Client, url: str, title: str) -> int | None:
    try:
        img = client.get(url, timeout=20, follow_redirects=True)
        if img.status_code != 200:
            return None
        safe = slugify(title)[:40] or "news"
        r = client.post(
            f"{WP_URL}/wp-json/wp/v2/media",
            content=img.content,
            headers={
                "Content-Disposition": f'attachment; filename="{safe}.jpg"',
                "Content-Type": "image/jpeg",
            },
            auth=AUTH,
        )
        if r.status_code in (200, 201):
            return r.json().get("id")
    except Exception as e:
        print(f"Image error: {e}")
    return None

def main():
    with httpx.Client(timeout=60) as client:
        published = 0
        for item in NEWS:
            media_id = upload_image(client, item["image"], item["title"])
            payload = {
                "title": item["title"],
                "content": item["content"],
                "status": "publish",
                "slug": slugify(item["title"]),
                "categories": [16],  # Футбол
            }
            if media_id:
                payload["featured_media"] = media_id
            r = client.post(f"{WP_URL}/wp-json/wp/v2/posts", json=payload, auth=AUTH)
            if r.status_code in (200, 201):
                link = r.json().get("link", "")
                print(f"OK: {item['title'][:50]} → {link}")
                published += 1
            else:
                print(f"ERR {r.status_code}: {item['title'][:40]}")
        print(f"\nОпубликовано: {published}/10")

if __name__ == "__main__":
    main()
