def slugify(text: str) -> str:
    result = []
    for ch in text.lower():
        result.append(TRANSLIT.get(ch, ch))
    s = "".join(result)
    s = re.sub(r"[^a-z0-9\-]", "-", s)
    s = re.sub(r"-+", "-", s).strip("-")
    return s[:80] or "news"

